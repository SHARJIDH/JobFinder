"""LaTeX resumes: built-in ATS-friendly template, safe compilation (Tectonic), page counting,
plain-text extraction and truthfulness checks for LaTeX edits.

Security: sources are scanned for shell-escape / file-access primitives before compiling, compilation
runs in an isolated temp directory with a timeout, and Tectonic never enables shell escape by default.
"""
from __future__ import annotations

import os
import re
import shutil
import subprocess
import tempfile
from dataclasses import dataclass
from pathlib import Path

from ..core.safety import numbers_in
from ..core.skills import extract_skills

# --------------------------------------------------------------------------- escaping

_ESC = {"\\": r"\textbackslash{}", "&": r"\&", "%": r"\%", "$": r"\$", "#": r"\#", "_": r"\_", "{": r"\{",
        "}": r"\}", "~": r"\textasciitilde{}", "^": r"\textasciicircum{}"}
_ESC_RE = re.compile(r"[\\&%$#_{}~^]")


def tex_escape(s: str) -> str:
    return _ESC_RE.sub(lambda m: _ESC[m.group(0)], s or "").replace("\u2013", "--").replace("\u2014", "---")


def _url(u: str) -> str:
    return re.sub(r"[{}\\%#]", "", u or "")


# --------------------------------------------------------------------------- built-in template

@dataclass
class Layout:
    font_pt: int = 11
    margin_in: float = 0.6
    item_sep_pt: float = 1.0
    section_space_pt: float = 6.0


def render_builtin(content: dict, layout: Layout | None = None) -> str:
    """Render tailored-resume content (the validated JSON from tailoring) into the built-in LaTeX template."""
    L = layout or Layout()
    c = content.get("contact", {})
    links = []
    for key in ("email", "phone", "location", "linkedin", "github", "portfolio"):
        v = (c.get(key) or "").strip()
        if not v:
            continue
        if key == "email":
            links.append(rf"\href{{mailto:{_url(v)}}}{{{tex_escape(v)}}}")
        elif v.startswith("http"):
            links.append(rf"\href{{{_url(v)}}}{{{tex_escape(re.sub(r'^https?://(www\.)?', '', v))}}}")
        else:
            links.append(tex_escape(v))

    def dates(s, e):
        return tex_escape(f"{s or '?'} -- {e or 'Present'}") if (s or e) else ""

    def items(bullets):
        if not bullets:
            return ""
        body = "\n".join(rf"  \item {tex_escape(b['text'])}" for b in bullets)
        return "\\begin{itemize}\n" + body + "\n\\end{itemize}\n"

    sep = " \\textbar{} "
    out = [rf"""\documentclass[{L.font_pt}pt,a4paper]{{article}}
\usepackage[margin={L.margin_in}in]{{geometry}}
\usepackage[hidelinks]{{hyperref}}
\usepackage{{enumitem}}
\usepackage{{titlesec}}
\usepackage[T1]{{fontenc}}
\usepackage{{lmodern}}
\setlength{{\parindent}}{{0pt}}
\pagestyle{{empty}}
\titleformat{{\section}}{{\large\bfseries\uppercase}}{{}}{{0em}}{{}}[\titlerule]
\titlespacing*{{\section}}{{0pt}}{{{L.section_space_pt}pt}}{{3pt}}
\setlist[itemize]{{leftmargin=1.2em, itemsep={L.item_sep_pt}pt, topsep=1pt, parsep=0pt, partopsep=0pt}}
\newcommand{{\entry}}[2]{{\par\textbf{{#1}}\hfill{{\small #2}}\par}}
% Generated by AI Job Hunter. Every line comes from your verified profile.
\begin{{document}}
\begin{{center}}
  {{\LARGE\bfseries {tex_escape(c.get('full_name') or 'Your Name')}}}\par\vspace{{2pt}}
  {{\small {sep.join(links)}}}
\end{{center}}
"""]
    if content.get("summary"):
        out.append("\\section{Summary}\n" + tex_escape(content["summary"]) + "\n")
    if content.get("skills"):
        out.append("\\section{Skills}\n" + tex_escape(", ".join(content["skills"])) + "\n")
    if content.get("experience"):
        out.append("\\section{Experience}")
        for x in content["experience"]:
            title = f"{x['title']} -- {x['company']}" if x.get("company") else x["title"]
            right = ", ".join(v for v in (tex_escape(x.get("location", "")), dates(x.get("start"), x.get("end"))) if v)
            out.append(rf"\entry{{{tex_escape(title)}}}{{{right}}}" + "\n" + items(x.get("bullets", [])))
    if content.get("projects"):
        out.append("\\section{Projects}")
        for p in content["projects"]:
            tech = f" {{\\normalfont\\textit{{({tex_escape(', '.join(p.get('technologies', [])))})}}}}" if p.get("technologies") else ""
            right = rf"\href{{{_url(p['url'])}}}{{link}}" if p.get("url", "").startswith("http") else ""
            out.append(rf"\entry{{{tex_escape(p['name'])}{tech}}}{{{right}}}" + "\n" + items(p.get("bullets", [])))
    if content.get("education"):
        out.append("\\section{Education}")
        for e in content["education"]:
            right = ", ".join(v for v in (dates(e.get("start"), e.get("end")), tex_escape(e.get("grade", ""))) if v)
            out.append(rf"\entry{{{tex_escape(e['degree'])} -- {tex_escape(e['institution'])}}}{{{right}}}")
    if content.get("certifications"):
        out.append("\\section{Certifications}\n" + items([{"text": " -- ".join(v for v in (x.get("name"), x.get("issuer"), x.get("date")) if v)}
                                                         for x in content["certifications"]]))
    if content.get("achievements"):
        out.append("\\section{Achievements}\n" + items([{"text": a} for a in content["achievements"]]))
    out.append("\\end{document}\n")
    return "\n".join(out)


# --------------------------------------------------------------------------- safety

_FORBIDDEN = [
    (r"\\write18|\\immediate\s*\\write|\\openout|\\openin|\\read\s*\d|\\newwrite|\\newread", "file or shell I/O"),
    (r"\\(input|include|InputIfFileExists|lstinputlisting|verbatiminput|includegraphics)\s*(\[[^\]]*\])?\s*\{\s*(/|~|\.\.)",
     "absolute or parent-directory file access"),
    (r"\\usepackage\s*(\[[^\]]*\])?\s*\{[^}]*\b(shellesc|bashful|pythontex|minted|catchfile)\b", "package that runs commands or reads files"),
    (r"\\(directlua|luaexec|ShellEscape|pdfshellescape)", "Lua/shell execution"),
]


def unsafe_reasons(src: str) -> list[str]:
    body = "\n".join(line.split("%", 1)[0] if not line.strip().startswith("\\%") else line for line in src.splitlines())
    return [why for pat, why in _FORBIDDEN if re.search(pat, body)]


# --------------------------------------------------------------------------- compile

@dataclass
class CompileResult:
    ok: bool
    pdf: bytes | None
    pages: int | None
    log: str


def compiler_path() -> str | None:
    return shutil.which(os.environ.get("TECTONIC_BIN", "tectonic"))


def compile_tex(src: str, timeout: int = 180) -> CompileResult:
    bad = unsafe_reasons(src)
    if bad:
        return CompileResult(False, None, None, "Refused to compile: source uses " + "; ".join(bad))
    exe = compiler_path()
    if not exe:
        return CompileResult(False, None, None, "No LaTeX compiler installed (install Tectonic: `brew install tectonic`).")
    with tempfile.TemporaryDirectory(prefix="jh-tex-") as d:
        tex = Path(d) / "resume.tex"
        tex.write_text(src, encoding="utf-8")
        try:
            p = subprocess.run([exe, "--keep-logs", "--outdir", d, str(tex)], cwd=d, capture_output=True, text=True,
                               timeout=timeout, env={**os.environ, "HOME": os.environ.get("HOME", d)})
        except subprocess.TimeoutExpired:
            return CompileResult(False, None, None, f"LaTeX compilation timed out after {timeout}s")
        log = (p.stdout + "\n" + p.stderr)[-12000:]
        pdf = Path(d) / "resume.pdf"
        if p.returncode != 0 or not pdf.exists():
            return CompileResult(False, None, None, _short_errors(log) or log)
        data = pdf.read_bytes()
    return CompileResult(True, data, page_count(data), _short_errors(log))


def _short_errors(log: str) -> str:
    lines = [ln for ln in log.splitlines() if re.search(r"(error|Error|!|Overfull|Undefined)", ln)]
    return "\n".join(lines[:40])


def page_count(pdf: bytes) -> int:
    import io

    from pypdf import PdfReader

    return len(PdfReader(io.BytesIO(pdf)).pages)


def page_images(pdf: bytes, scale: float = 1.2, max_pages: int = 3, first: int = 0) -> list[bytes]:
    """PNG screenshots of pages (shown to Gemini to fix overflow, and used as the editor preview)."""
    import io

    import pypdfium2 as pdfium

    doc = pdfium.PdfDocument(pdf)
    out = []
    for i in range(first, min(len(doc), first + max_pages)):
        img = doc[i].render(scale=scale).to_pil()
        buf = io.BytesIO()
        img.save(buf, format="PNG", optimize=True)
        out.append(buf.getvalue())
    doc.close()
    return out


# --------------------------------------------------------------------------- text & truthfulness

def tex_to_text(src: str) -> str:
    """Rough detex: drop comments/preamble/commands, keep visible text."""
    body = src.split("\\begin{document}", 1)[-1]
    body = "\n".join(re.sub(r"(?<!\\)%.*", "", ln) for ln in body.splitlines())
    body = re.sub(r"\\\\(\[[^\]]*\])?", " ", body)
    body = re.sub(r"\\(href)\{[^}]*\}", " ", body)
    body = re.sub(r"\\(?:begin|end)\{[^}]*\}", " ", body)
    body = re.sub(r"\\[a-zA-Z@]+\*?(\[[^\]]*\])?", " ", body)
    body = body.replace("\\&", "&").replace("\\%", "%").replace("\\$", "$").replace("\\#", "#").replace("\\_", "_")
    body = re.sub(r"[{}]", " ", body)
    return re.sub(r"[ \t]+", " ", body)


def unsupported_changes(new_src: str, allowed_text: str, usable_skills: list[str]) -> dict:
    """Numbers and skills that appear in the new LaTeX but in none of the allowed sources."""
    new_text = tex_to_text(new_src)
    allowed_nums = numbers_in(allowed_text)
    plain = {re.sub(r"[%xkm]$", "", n) for n in allowed_nums}
    nums = sorted(n for n in numbers_in(new_text) if n not in allowed_nums and re.sub(r"[%xkm]$", "", n) not in plain)
    allowed_sk = {s.lower() for s in usable_skills} | {s.lower() for s in extract_skills(allowed_text)}
    skills = sorted(s for s in extract_skills(new_text) if s.lower() not in allowed_sk)
    return {"numbers": nums, "skills": skills}
